  /* Theme ---------------------------------------------------- */
  function initTheme() {
    const root = document.documentElement;
    const toggle = $("[data-theme-toggle]");
    const label = $("[data-theme-label]");
    const meta = $('meta[name="theme-color"]');

    const apply = (theme) => {
      root.dataset.theme = theme;
      if (label) label.textContent = theme === "dark" ? "Dark" : "Light";
      if (toggle) {
        toggle.setAttribute(
          "aria-label",
          theme === "dark" ? "Switch to light mode" : "Switch to dark mode"
        );
      }
      if (meta) meta.setAttribute("content", theme === "dark" ? "#0B0B0B" : "#F2EFE7");
    };

    apply(root.dataset.theme || "light");

    if (!toggle) return;

    toggle.addEventListener("click", () => {
      const next = root.dataset.theme === "dark" ? "light" : "dark";
      apply(next);
      try {
        localStorage.setItem("theme", next);
      } catch (error) {
        /* Storage can be unavailable in private browsing; the theme still changes. */
      }
    });
  }

  /* Clock ---------------------------------------------------- */
  function initClock() {
    const clocks = $$("[data-clock]");
    if (!clocks.length) return;

    const formatter = new Intl.DateTimeFormat("en-GB", {
      timeZone: "Africa/Lagos",
      hour: "2-digit",
      minute: "2-digit",
      hour12: false
    });

    const update = () => {
      const now = new Date();
      const time = formatter.format(now);
      clocks.forEach((clock) => {
        clock.textContent = time;
        clock.setAttribute("datetime", now.toISOString());
      });
    };

    update();
    window.setInterval(update, 30000);
  }

  /* Preview panel ------------------------------------------- */
  function initPreviews() {
    const workList = $(".work-list");
    const videos = $$(".preview-video");
    const kicker = $("[data-preview-kicker]");
    const name = $("[data-preview-name]");
    const caption = $("[data-preview-caption]");
    const foot = $$(".preview-foot span");

    if (!workList || !videos.length) return;

    const pauseAll = () => {
      videos.forEach((video) => video.pause());
    };

    const setActive = (slug, play = true) => {
      const preview = previews[slug];
      if (!preview) return;

      $$(".project-row", workList).forEach((row) => {
        row.classList.toggle("is-active", row.dataset.project === slug);
      });

      videos.forEach((video) => {
        const active = video.dataset.preview === slug;
        video.classList.toggle("is-active", active);

        if (active && play && !reducedMotion.matches) {
          const attempt = video.play();
          if (attempt && typeof attempt.catch === "function") {
            attempt.catch(() => {
              /* Autoplay can be blocked; the poster remains visible. */
            });
          }
        } else if (!active) {
          video.pause();
        }
      });

      if (kicker) kicker.textContent = `[${preview.number}] / ${preview.category}`;
      if (name) name.textContent = preview.name;
      if (caption) caption.textContent = preview.caption;

      foot.forEach((item, index) => {
        if (preview.foot[index]) item.textContent = preview.foot[index];
      });
    };

    $$(".project-row", workList).forEach((row) => {
      const slug = row.dataset.project;

      row.addEventListener("pointerenter", () => setActive(slug, true));
      row.addEventListener("focus", () => setActive(slug, true));
    });

    workList.addEventListener("pointerleave", () => {
      if (!workList.contains(document.activeElement)) pauseAll();
    });

    workList.addEventListener("focusout", () => {
      window.requestAnimationFrame(() => {
        if (!workList.contains(document.activeElement)) pauseAll();
      });
    });

    document.addEventListener("visibilitychange", () => {
      if (document.hidden) pauseAll();
    });

    setActive("goodnews", false);
  }

